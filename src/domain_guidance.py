# Fail loudly at import if the taxonomy and the modules ever drift apart.
_missing = sorted(set(DOMAIN_TAGS) - set(_MODULES))
if _missing:  # pragma: no cover - guards a developer mistake, not runtime input
    raise RuntimeError(f"domain tags without a guidance module: {_missing}")


def known_tags() -> Sequence[str]:
    """The controlled taxonomy, in canonical order."""
    return DOMAIN_TAGS


def normalize_tags(tags: Optional[Iterable[str]]) -> List[str]:
    """Filter to known tags, de-duplicate (first wins), and bound the count.

    Defensive: routing must never crash scene generation. Unknown tags are
    rejected at the schema boundary; anything odd that reaches here is dropped
    and the safe "general" default applies.
    """
    out: List[str] = []
    for tag in tags or ():
        if not isinstance(tag, str):
            continue
        key = tag.strip().lower().replace("-", "_").replace(" ", "_")
        if key in _MODULES and key not in out:
            out.append(key)
    if not out:
        return ["general"]
    # A specialist tag makes a co-selected "general" meaningless.
    if len(out) > 1:
        out = [t for t in out if t != "general"] or ["general"]
    return out[:MAX_TOTAL_DOMAIN_TAGS]


def modules_for(tags: Optional[Iterable[str]]) -> List[str]:
    """Return the selected tags (normalized) — the audit view of routing."""
    return normalize_tags(tags)


def build_domain_section(tags: Optional[Iterable[str]]) -> str:
    """Assemble the domain guidance block for the selected tags only.

    A bare "general" scene gets the short general module without the accuracy
    preamble (it makes no domain claims); any specialist scene gets the
    accuracy rule plus its 1-3 modules, primary first.
    """
    selected = normalize_tags(tags)
    if selected == ["general"]:
        return f"{_DOMAIN_HEADER}\n\n{_GENERAL}"
    body = "\n\n".join(_MODULES[t] for t in selected)
    return f"{_DOMAIN_HEADER}\n\n{_ACCURACY_RULE}\n\n{body}"


