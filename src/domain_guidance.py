"""Per-domain visual-reasoning guidance, selected by storyboard domain tags.

Previously every scene received one ~5,200-token block covering every maths and
physics topic at once. Flash-Lite has ample context for that, so this is not a
capacity fix — it is an *instruction-dilution* fix: a calculus scene that also
reads magnetism, optics and astrophysics rules follows its own rules less
consistently and drifts toward generic diagrams.

Each module below is the concise, animation-relevant slice for one tag in
:data:`schemas.DOMAIN_TAGS`. Modules state visual opportunities and correctness
constraints; they never prescribe a fixed diagram or a scene template.

Every Manim construct referenced here was render-verified in this environment
(Manim CE 0.19.1, cairo, no LaTeX) before being written down — notably the
cobweb/staircase iteration diagram, ``Cross(Circle(...))`` for into-page field
symbols, ``Angle`` / ``RightAngle`` marks, and ``Polygon`` trapezia. The
``BarChart`` class is excluded on purpose: its ``__init__`` builds ``Tex``
labels and therefore requires a LaTeX binary that is not installed.
"""

